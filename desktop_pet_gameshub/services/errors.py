"""Исключения сетевого/интеграционного слоя.

Отдельные типы ошибок позволяют UI показывать понятный статус ("нет сети",
"не удалось разобрать страницу") вместо сырого текста исключения.
"""

from __future__ import annotations


class NetworkError(Exception):
    """Не удалось выполнить сетевой запрос (таймаут, отсутствие сети, HTTP-ошибка)."""


class ParseError(Exception):
    """Страница получена, но не удалось извлечь из неё нужные данные."""
